/* ------------------------------------------------
   ELEMENT REFS
   ------------------------------------------------ */
const nav            = document.getElementById('nav');
const searchInput    = document.getElementById('searchInput');
const searchBtn      = document.getElementById('searchBtn');
const resultsSection = document.getElementById('results-section');
const resultsGrid    = document.getElementById('resultsGrid');
const resultsTitle   = document.getElementById('resultsTitle');
const resultsCount   = document.getElementById('resultsCount');
const modalOverlay   = document.getElementById('modal-overlay');
const modalIframe    = document.getElementById('modalIframe');
const modalPricing   = document.getElementById('modalPricing');
const modalLoading   = document.getElementById('modalLoading');
const modalName      = document.getElementById('modalBusinessName');
const modalBuyBtn    = document.getElementById('modalPurchaseBtn');
const modalClose     = document.getElementById('modalClose');


/* ------------------------------------------------
   DATA LOADING
   Reads previews/manifest.json — auto-generated by build.py on every
   Vercel deploy. Add a new client by pushing their folder + meta.json;
   Vercel rebuilds and the manifest updates automatically.
   For local dev: python -m http.server 8080
   ------------------------------------------------ */
let businesses = [];

async function loadBusinesses() {
    try {
        const res = await fetch('previews/manifest.json');
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        businesses = await res.json();
    } catch (err) {
        console.warn('Could not load previews/manifest.json:', err.message);
        businesses = null;
    }
}

loadBusinesses();

function updatePlaceholder() {
    searchInput.placeholder = window.innerWidth < 640
        ? 'Search your business…'
        : 'Search your business name…';
}
updatePlaceholder();
window.addEventListener('resize', updatePlaceholder, { passive: true });


/* ------------------------------------------------
   SEARCH
   ------------------------------------------------ */
searchInput.addEventListener('input', () => {
    const q = searchInput.value.trim();
    if (q.length >= 2) {
        runSearch(q);
    } else {
        hideResults();
    }
});

searchInput.addEventListener('keydown', e => {
    if (e.key === 'Enter') {
        const q = searchInput.value.trim();
        if (q.length >= 2) {
            runSearch(q);
            resultsSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
        }
    }
});

searchBtn.addEventListener('click', () => {
    const q = searchInput.value.trim();
    if (q.length < 2) return;
    runSearch(q);
    resultsSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
});

function runSearch(query) {
    if (businesses === null) {
        /* Data failed to load — show setup instructions */
        resultsSection.classList.add('visible');
        resultsTitle.textContent = 'Setup required';
        resultsCount.textContent = '';
        resultsGrid.innerHTML = `
            <div class="load-error">
                <strong>Could not load business data.</strong><br><br>
                This page needs to be served over HTTP, not opened as a local file.<br><br>
                Run: <code>python build.py</code> then <code>python -m http.server 8080</code><br><br>
                Then visit <code>http://localhost:8080</code> in your browser.
            </div>`;
        return;
    }

    const q = query.toLowerCase();
    const matches = businesses.filter(b =>
        b.name.toLowerCase().includes(q)     ||
        b.category.toLowerCase().includes(q) ||
        b.city.toLowerCase().includes(q)
    );

    renderResults(matches, query);
}

function renderResults(list, query) {
    resultsSection.classList.add('visible');

    if (list.length > 0) {
        resultsTitle.textContent = `Results for "${query}"`;
        resultsCount.textContent = `${list.length} website${list.length !== 1 ? 's' : ''} ready to preview`;
        resultsGrid.innerHTML = list.map(b => businessCard(b)).join('');
    } else {
        resultsTitle.textContent = `No results for "${query}"`;
        resultsCount.textContent = '';
        resultsGrid.innerHTML = `
            <div class="no-results">
                <p class="no-results-title">We haven't built a site for "${escHtml(query)}" yet.</p>
                <p class="no-results-sub">
                    Want one?
                    <a href="mailto:lukewebsitemarket@gmail.com?subject=New%20Website%20Request&body=Hi%2C%20I%27d%20like%20a%20website%20for%20my%20business.">
                        Reach out and we'll get started →
                    </a>
                </p>
            </div>`;
    }
}

function hideResults() {
    resultsSection.classList.remove('visible');
}

function businessCard(b) {
    const tags = (b.features || [])
        .map(f => `<span class="feature-tag">${escHtml(f)}</span>`)
        .join('');

    return `
        <div class="business-card" onclick="openPreview('${escAttr(b.id)}')" role="button" tabindex="0"
             aria-label="Preview website for ${escAttr(b.name)}"
             onkeydown="if(event.key==='Enter'||event.key===' ')openPreview('${escAttr(b.id)}')">
            <p class="card-category">${escHtml(b.category)}</p>
            <h3 class="card-name">${escHtml(b.name)}</h3>
            <p class="card-city">${escHtml(b.city)}</p>
            <div class="card-features">${tags}</div>
            <div class="card-footer">
                <span class="card-btn">Preview Site →</span>
            </div>
        </div>`;
}


/* ------------------------------------------------
   PREVIEW MODAL
   ------------------------------------------------ */
function openPreview(businessId) {
    const biz = businesses && businesses.find(b => b.id === businessId);
    if (!biz) return;

    modalName.textContent = biz.name;

    /* Purchase button — show Stripe pricing table */
    modalBuyBtn.innerHTML = '<span class="btn-text-full">Purchase This Website</span><span class="btn-text-short">Buy</span>';
    modalBuyBtn.onclick = () => showPricing(biz.id, biz.tier || 1);
    hidePricing();

    /* Show loading state then load the iframe */
    modalLoading.style.display = 'flex';
    modalIframe.src = '';

    modalIframe.onload = () => {
        /* Small delay so the page actually renders before we hide the spinner */
        setTimeout(() => { modalLoading.style.display = 'none'; }, 200);
    };

    modalIframe.src = `${biz.previewPath}/index.html`;

    modalOverlay.classList.add('open');
    document.body.style.overflow = 'hidden';
}

function showPricing(businessId, tier) {
    const t3 = tier === 3;
    const setup   = t3 ? '$1,000' : '$750';
    const monthly = t3 ? '$100'   : '$75';
    const yearly  = t3 ? '$1,000' : '$750';
    const savings = t3 ? 'Save $200 vs monthly' : 'Save $150 vs monthly';

    modalIframe.style.display = 'none';
    modalLoading.style.display = 'none';
    modalPricing.style.display = 'block';
    modalPricing.innerHTML = `
        <div class="pricing-wrap">
            <h2 class="pricing-title">Get your website live</h2>
            <p class="pricing-sub">${setup} one-time setup fee included with your first payment.</p>
            <div class="pricing-plans">
                <button class="plan-card" onclick="startCheckout('${escAttr(businessId)}','monthly',${tier || 2})">
                    <span class="plan-name">Monthly</span>
                    <span class="plan-price">${monthly}<em>/mo</em></span>
                    <span class="plan-note">Cancel anytime</span>
                </button>
                <button class="plan-card plan-card--featured" onclick="startCheckout('${escAttr(businessId)}','yearly',${tier || 2})">
                    <span class="plan-name">Yearly</span>
                    <span class="plan-price">${yearly}<em>/yr</em></span>
                    <span class="plan-note">${savings}</span>
                </button>
            </div>
            <p class="pricing-legal">${setup} setup + your chosen plan charged today. Renews automatically.</p>
        </div>`;
    modalBuyBtn.innerHTML = '← Back to preview';
    modalBuyBtn.onclick = () => hidePricing();
}

async function startCheckout(businessId, plan, tier) {
    try {
        const res = await fetch('/api/checkout', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ plan, businessId, tier: tier || 1 }),
        });
        const { url } = await res.json();
        window.location.href = url;
    } catch (err) {
        alert('Something went wrong. Please try again.');
    }
}

window.startCheckout = startCheckout;

function hidePricing() {
    modalPricing.style.display = 'none';
    modalPricing.innerHTML = '';
    modalIframe.style.display = '';
}

function closeModal() {
    modalOverlay.classList.remove('open');
    modalIframe.src = '';
    hidePricing();
    document.body.style.overflow = '';
}

/* Close on overlay click (but not on modal click) */
modalOverlay.addEventListener('click', e => {
    if (e.target === modalOverlay) closeModal();
});

modalClose.addEventListener('click', closeModal);

document.addEventListener('keydown', e => {
    if (e.key === 'Escape' && modalOverlay.classList.contains('open')) closeModal();
});

/* Expose to onclick in HTML */
window.openPreview = openPreview;


/* ------------------------------------------------
   DEMO REQUEST MODAL
   ------------------------------------------------ */
const demoOverlay = document.getElementById('demo-modal-overlay');

function openDemoModal() {
    demoOverlay.classList.add('open');
    document.body.style.overflow = 'hidden';
}

function closeDemoModal() {
    demoOverlay.classList.remove('open');
    document.body.style.overflow = '';
    document.getElementById('demoForm').style.display = '';
    document.getElementById('demoForm').reset();
    document.getElementById('demoSuccess').style.display = 'none';
}

async function submitDemo(e) {
    e.preventDefault();
    const company = document.getElementById('demoCompany').value.trim();
    const contact = document.getElementById('demoContact').value.trim();
    const details = document.getElementById('demoDetails').value.trim();
    try {
        const res = await fetch('/api/contact', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ company, contact, details }),
        });
        if (res.ok) {
            document.getElementById('demoForm').style.display = 'none';
            document.getElementById('demoSuccess').style.display = 'block';
        } else {
            alert('Something went wrong. Please try again.');
        }
    } catch {
        alert('Something went wrong. Please try again.');
    }
}

demoOverlay.addEventListener('click', e => { if (e.target === demoOverlay) closeDemoModal(); });
document.addEventListener('keydown', e => {
    if (e.key === 'Escape' && demoOverlay.classList.contains('open')) closeDemoModal();
});

window.openDemoModal  = openDemoModal;
window.closeDemoModal = closeDemoModal;
window.submitDemo     = submitDemo;



